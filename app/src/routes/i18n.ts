export function tr(text: string, lang: Lang): string {
 if(lang==='en') return text;
 const d=translations[lang];
 if(d[text]) return d[text];
 // Preserve English names when a translation is not available; never guess allergen information.
 const chunks=text.split(' · ');
 if(chunks.length>1) return chunks.map(x=>tr(x,lang)).join(' · ');
 // Translate common compound menu names using known ingredient names.
 const parts=Object.keys(d).filter(x=>['Black Sesame','Salted Caramel','Red Bean','Injeolmi','Strawberry','Matcha','Mugwort','Pandan','Peach','Dolce','Ube','Einspanner','Bingsu','Tiramisu','Mochi','w/ Espresso','(Unsweet)','(Sweet)'].includes(x)).sort((a,b)=>b.length-a.length);
 let result=text;
 for(const part of parts) result=result.replace(part,d[part]);
 return result;
}
